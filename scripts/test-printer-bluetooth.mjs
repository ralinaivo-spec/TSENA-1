const total = c.reduce((t, x) => t + x.length, 0), max = Math.max(...c.map(x => x.length));
const tail = c.flat().slice(-6).map(x => x.toString(16)).join(' ');
console.log('chunks', c.length, 'bytes', total, 'max chunk', max, 'tail', tail);
